#!/usr/bin/env node

/**
 * Exchange Rate Seed Generator
 * Reads EUR/BRL historical CSV from investing.com and generates SQL seed.
 *
 * Usage: node supabase/seeds/prod/scripts/generate-exchange-rates.cjs
 * Input:  supabase/seeds/prod/raw/eur_brl_historical_rates.csv
 * Output: supabase/seeds/prod/03_import_exchange_rates.sql
 */

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');

const SCRIPT_DIR = __dirname;
const RAW_DIR = path.join(SCRIPT_DIR, '..', 'raw');
const OUTPUT_FILE = path.join(SCRIPT_DIR, '..', '03_import_exchange_rates.sql');
const INPUT_FILE = path.join(RAW_DIR, 'eur_brl_historical_rates.csv');

/**
 * Parse MM/DD/YYYY → YYYY-MM-DD
 */
function parseDate(dateStr) {
  const cleaned = dateStr.replace(/"/g, '').trim();
  const parts = cleaned.split('/');
  if (parts.length !== 3) return null;
  const [month, day, year] = parts;
  return `${year}-${month.padStart(2, '0')}-${day.padStart(2, '0')}`;
}

/**
 * Returns true if the date falls on a weekend (Saturday=6, Sunday=0)
 */
function isWeekend(dateStr) {
  const d = new Date(dateStr + 'T00:00:00Z');
  const day = d.getUTCDay();
  return day === 0 || day === 6;
}

function main() {
  console.log('========================================');
  console.log('📈 Exchange Rate Seed Generator');
  console.log('========================================');

  if (!fs.existsSync(INPUT_FILE)) {
    console.error(`❌ Input file not found: ${INPUT_FILE}`);
    console.error('   Download EUR/BRL historical data from investing.com and place it at:');
    console.error(`   ${INPUT_FILE}`);
    process.exit(1);
  }

  const content = fs.readFileSync(INPUT_FILE, 'utf-8');
  const cleanContent = content.replace(/^\uFEFF/, ''); // strip BOM
  const rows = parse(cleanContent, {
    columns: true,
    skip_empty_lines: true,
    trim: true
  });

  const values = [];
  let skippedWeekends = 0;
  let skippedInvalid = 0;

  for (const row of rows) {
    const dateStr = parseDate(row['Date']);
    if (!dateStr) {
      skippedInvalid++;
      continue;
    }

    // Skip weekends — ECB doesn't publish rates on weekends, consistent with Frankfurter
    if (isWeekend(dateStr)) {
      skippedWeekends++;
      continue;
    }

    const price = parseFloat(row['Price']);
    if (!price || isNaN(price) || price <= 0) {
      skippedInvalid++;
      continue;
    }

    // CSV Price = EUR/BRL (how many BRL per 1 EUR)
    // rate_to_eur = how many EUR per 1 BRL = 1 / price
    const rateToEur = (1 / price).toFixed(6);
    values.push(`  ('BRL', '${dateStr}', ${rateToEur})`);
  }

  console.log(`\n  ✓ Parsed ${rows.length} rows`);
  console.log(`    • Valid rates: ${values.length}`);
  console.log(`    • Skipped weekends: ${skippedWeekends}`);
  console.log(`    • Skipped invalid: ${skippedInvalid}`);

  if (values.length === 0) {
    console.error('❌ No valid rates found. Check CSV format.');
    process.exit(1);
  }

  // Show date range
  const dates = values.map(v => v.match(/'(\d{4}-\d{2}-\d{2})'/)[1]).sort();
  console.log(`    • Date range: ${dates[0]} → ${dates[dates.length - 1]}`);

  const sql = `-- ============================================================================
-- 03_import_exchange_rates.sql - Import Exchange Rates
-- ============================================================================
-- Auto-generated by scripts/generate-exchange-rates.cjs
-- Do not edit manually - run \`npm run seed:exchange-rates\` to regenerate
-- Source: supabase/seeds/prod/raw/eur_brl_historical_rates.csv
-- Generated: ${new Date().toISOString()}
-- Rows: ${values.length} (${dates[0]} to ${dates[dates.length - 1]})
-- ============================================================================

DO $$
DECLARE
  imported_count INTEGER;
BEGIN
  RAISE NOTICE '========================================';
  RAISE NOTICE '[EXCHANGE RATES] Importing historical EUR/BRL exchange rates...';
  RAISE NOTICE '========================================';

  INSERT INTO public.exchange_rates (currency, rate_date, rate_to_eur) VALUES
${values.join(',\n')}
  ON CONFLICT (currency, rate_date) DO NOTHING;

  GET DIAGNOSTICS imported_count = ROW_COUNT;
  RAISE NOTICE '  ✓ Imported % exchange rates (skipped existing)', imported_count;

  RAISE NOTICE '========================================';
END $$;
`;

  fs.writeFileSync(OUTPUT_FILE, sql, 'utf-8');

  console.log(`\n📁 Output: ${OUTPUT_FILE}`);
  console.log('========================================\n');
}

main();
