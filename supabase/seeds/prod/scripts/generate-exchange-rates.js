#!/usr/bin/env node

/**
 * Exchange Rate Generator for Historical Data
 * Fetches historical exchange rates for dates/currencies in expense data
 *
 * Usage: node generate-exchange-rates.js
 * Input: Reads expenses from normalized/expenses.csv
 * Output: Generates SQL file with exchange rate inserts
 */

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');

// Load config
const SCRIPT_DIR = __dirname;
let config;
try {
  config = require('./config.local');
  console.log('Using config.local.js');
} catch (e) {
  config = require('./config');
  console.log('Using config.js template');
}

const NORMALIZED_DIR = path.join(SCRIPT_DIR, '..', config.paths.normalized);
const EXPENSES_FILE = path.join(NORMALIZED_DIR, 'expenses.csv');
const SEED_DIR = path.join(SCRIPT_DIR, '..');
const OUTPUT_FILE = path.join(SEED_DIR, '03_import_exchange_rates.sql');

/**
 * Fetch exchange rate from API
 */
async function fetchExchangeRate(currency, date) {
  if (currency === 'EUR') {
    return 1.0;
  }

  const url = `https://api.exchangerate.host/${date}?base=EUR&symbols=${currency}`;

  try {
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`API responded with status ${response.status}`);
    }

    const data = await response.json();
    if (!data.success) {
      throw new Error('API request was not successful');
    }

    const rate = data.rates[currency];
    if (!rate) {
      throw new Error(`Rate not found for currency ${currency}`);
    }

    // Convert from EUR-to-currency to currency-to-EUR
    return 1 / rate;

  } catch (error) {
    console.warn(`Failed to fetch ${currency} rate for ${date}:`, error.message);

    // Fallback rates
    const fallbackRates = {
      BRL: 0.17,
      USD: 0.92,
      GBP: 1.17,
      CHF: 1.05,
      JPY: 0.0062,
      CAD: 0.65,
    };

    return fallbackRates[currency] || 1.0;
  }
}

/**
 * Delay helper to avoid rate limiting
 */
function delay(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

/**
 * Generate SQL INSERT statements
 */
function generateSql(rates) {
  const lines = [];
  lines.push('-- ============================================================================');
  lines.push('-- 03_import_exchange_rates.sql - Import Exchange Rates');
  lines.push('-- ============================================================================');
  lines.push('-- Auto-generated by generate-exchange-rates.js');
  lines.push(`-- Generated: ${new Date().toISOString()}`);
  lines.push('-- ============================================================================');
  lines.push('');

  if (rates.length === 0) {
    lines.push('-- No exchange rates to import (all expenses in EUR)');
    return lines.join('\n');
  }

  lines.push('DO $$');
  lines.push('DECLARE');
  lines.push('  imported_count INTEGER;');
  lines.push('BEGIN');
  lines.push('  RAISE NOTICE \'========================================\';');
  lines.push('  RAISE NOTICE \'[EXCHANGE RATES] Importing historical exchange rates...\';');
  lines.push('  RAISE NOTICE \'========================================\';');
  lines.push('');
  lines.push('  INSERT INTO public.exchange_rates (currency, rate_date, rate_to_eur) VALUES');

  const values = rates.map((row, index) => {
    const isLast = index === rates.length - 1;
    return `    ('${row.currency}', '${row.date}', ${row.rate})${isLast ? ';' : ','}`;
  });

  lines.push(...values);
  lines.push('');
  lines.push('  GET DIAGNOSTICS imported_count = ROW_COUNT;');
  lines.push('  RAISE NOTICE \'  ✓ Imported % exchange rates\', imported_count;');
  lines.push('');
  lines.push('  RAISE NOTICE \'========================================\';');
  lines.push('END $$;');

  return lines.join('\n');
}

/**
 * Main execution
 */
async function main() {
  console.log('🔍 Reading expenses data...');

  if (!fs.existsSync(EXPENSES_FILE)) {
    console.error(`❌ Expenses file not found: ${EXPENSES_FILE}`);
    console.log('Run: npm run seed:transform first');
    process.exit(1);
  }

  const content = fs.readFileSync(EXPENSES_FILE, 'utf-8');
  const cleanContent = content.replace(/^\uFEFF/, '');
  const expenses = parse(cleanContent, {
    columns: true,
    skip_empty_lines: true,
    trim: true
  });

  console.log(`📊 Found ${expenses.length} expenses`);

  // Extract unique (currency, date) pairs for non-EUR currencies
  const uniquePairs = new Set();
  expenses.forEach(expense => {
    const currency = expense.currency;
    const date = expense.expense_date;

    if (currency && currency !== 'EUR' && date) {
      uniquePairs.add(`${currency}|${date}`);
    }
  });

  console.log(`💱 Found ${uniquePairs.size} unique (currency, date) pairs to fetch`);

  // Convert to array and sort
  const pairs = Array.from(uniquePairs)
    .map(pair => {
      const [currency, date] = pair.split('|');
      return { currency, date };
    })
    .sort((a, b) => {
      // Sort by date first, then currency
      if (a.date !== b.date) return a.date.localeCompare(b.date);
      return a.currency.localeCompare(b.currency);
    });

  // Fetch rates with progress indicator
  console.log('🌐 Fetching exchange rates from API...');
  const rates = [];
  let fetched = 0;

  for (const pair of pairs) {
    try {
      const rate = await fetchExchangeRate(pair.currency, pair.date);
      rates.push({
        currency: pair.currency,
        date: pair.date,
        rate: rate
      });

      fetched++;
      if (fetched % 10 === 0) {
        console.log(`   Progress: ${fetched}/${pairs.length}`);
      }

      // Rate limit: 100ms between requests
      await delay(100);

    } catch (error) {
      console.error(`❌ Failed to fetch ${pair.currency} for ${pair.date}:`, error.message);
    }
  }

  console.log(`✅ Fetched ${rates.length} exchange rates`);

  // Generate SQL
  console.log('📝 Generating SQL file...');
  const sql = generateSql(rates);
  fs.writeFileSync(OUTPUT_FILE, sql, 'utf-8');
  console.log(`✅ Written to: ${OUTPUT_FILE}`);

  // Summary by currency
  const byCurrency = {};
  rates.forEach(r => {
    byCurrency[r.currency] = (byCurrency[r.currency] || 0) + 1;
  });

  console.log('\n📈 Summary:');
  Object.entries(byCurrency)
    .sort((a, b) => b[1] - a[1])
    .forEach(([currency, count]) => {
      console.log(`   ${currency}: ${count} rates`);
    });

  console.log('\n✨ Done! You can now run: npm run seed:reset');
}

main().catch(error => {
  console.error('💥 Error:', error);
  process.exit(1);
});
